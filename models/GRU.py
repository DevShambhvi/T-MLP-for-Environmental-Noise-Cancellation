# ============================================================
# DETERMINISTIC EXPERIMENT CONTROLS
# ============================================================

SEED = 42

random.seed(SEED)
np.random.seed(SEED)
tf.random.set_seed(SEED)

# Force deterministic TensorFlow operations where supported
tf.config.experimental.enable_op_determinism()


# ============================================================
# EXPERIMENT CONFIGURATION
# ============================================================

EXPERIMENT_NAME = "GRU_baseline"

DATASET_PATH = "/content/drive/MyDrive/T-MLP/processed_data"

TRAIN_PATH = os.path.join(DATASET_PATH, "train")
VAL_PATH = os.path.join(DATASET_PATH, "validation")
TEST_PATH = os.path.join(DATASET_PATH, "test")

EXPECTED_TRAIN = 800
EXPECTED_VAL = 100
EXPECTED_TEST = 100

WINDOW_SIZE = 256
HOP_SIZE = 128

BATCH_SIZE = 32
EPOCHS = 10
LEARNING_RATE = 0.01

MODEL_SAVE_PATH = "/content/GRU.keras"


# ============================================================
# ENVIRONMENT
# ============================================================

print("\nEnvironment")
print("----------------------------------------")
print("Experiment:", EXPERIMENT_NAME)
print("TensorFlow:", tf.__version__)
print("Random seed:", SEED)
print("Deterministic operations: ENABLED")


# ============================================================
# DATASET VERIFICATION
# ============================================================

print("\nDataset verification")
print("----------------------------------------")

train_files = sorted(
    glob.glob(os.path.join(TRAIN_PATH, "*.npz"))
)

val_files = sorted(
    glob.glob(os.path.join(VAL_PATH, "*.npz"))
)

test_files = sorted(
    glob.glob(os.path.join(TEST_PATH, "*.npz"))
)

print(f"Training samples   : {len(train_files)}")
print(f"Validation samples : {len(val_files)}")
print(f"Test samples       : {len(test_files)}")

