# 5. LOAD DATA
# ============================================================

print("\nLoading training data...")

X_train, Y_train = load_windows(train_files)

print(
    f"Training windows: {len(X_train)}"
)


print("\nLoading validation data...")

X_val, Y_val = load_windows(val_files)

print(
    f"Validation windows: {len(X_val)}"
)


print("\nLoading test data...")

X_test, Y_test = load_windows(test_files)

print(
    f"Test windows: {len(X_test)}"
)


# ============================================================
# 6. TF.DATA PIPELINE
# ============================================================

train_dataset = tf.data.Dataset.from_tensor_slices(
    (X_train, Y_train)
)

train_dataset = (
    train_dataset
    .shuffle(
        buffer_size=len(X_train),
        reshuffle_each_iteration=True
    )
    .batch(BATCH_SIZE)
    .prefetch(tf.data.AUTOTUNE)
)


val_dataset = tf.data.Dataset.from_tensor_slices(
    (X_val, Y_val)
)

val_dataset = (
    val_dataset
    .batch(BATCH_SIZE)
    .prefetch(tf.data.AUTOTUNE)
)


# ============================================================
# 7. BUILD QAT-COMPATIBLE T-MLP
# ============================================================
#
# IMPORTANT:
#
# We intentionally DO NOT use a custom Keras Layer here.
#
# Instead:
#
# Dense -> Dense -> Add
#
# is explicitly constructed using standard Keras layers.
#
# This allows TFMOT to recognize and quantize the layers.
#
# ============================================================

def build_tmlp_qat_base():

    inputs = tf.keras.Input(
        shape=(WINDOW_SIZE,),
        name="noisy_audio"
    )

    # --------------------------------------------------------
    # Input:
    # (batch, 256)
    #
    # Reshape:
    # (batch, 256, 1)
    # --------------------------------------------------------

    x = tf.keras.layers.Reshape(
        (WINDOW_SIZE, 1),
        name="input_reshape"
    )(inputs)

    # --------------------------------------------------------
    # Feature projection
    #
    # 1 -> 64
    # --------------------------------------------------------

    x = tf.keras.layers.Dense(
        64,
        activation="relu",
        name="feature_projection"
    )(x)

    # ========================================================
    # TEMPORAL MLP BLOCK 1
    # ========================================================

    residual_1 = x

    x = tf.keras.layers.Dense(
        64,
        activation="relu",
        name="block1_dense1"
    )(x)

    x = tf.keras.layers.Dense(
        64,
        activation=None,
        name="block1_dense2"
    )(x)

    x = tf.keras.layers.Add(
        name="block1_residual_add"
    )([
        residual_1,
        x
    ])

    # ========================================================
    # TEMPORAL MLP BLOCK 2
    # ========================================================

    residual_2 = x

    x = tf.keras.layers.Dense(
        64,
        activation="relu",
        name="block2_dense1"
    )(x)

    x = tf.keras.layers.Dense(
        64,
        activation=None,
        name="block2_dense2"
    )(x)

    x = tf.keras.layers.Add(
        name="block2_residual_add"
    )([
        residual_2,
        x
    ])

    # ========================================================
    # OUTPUT PROJECTION
    # ========================================================

    x = tf.keras.layers.Dense(
        32,
        activation="relu",
        name="output_projection"
    )(x)

    x = tf.keras.layers.Dense(
        1,
        activation=None,
        name="audio_output"
    )(x)

    # --------------------------------------------------------
    # (batch, 256, 1)
    #
    # ->
    #
    # (batch, 256)
    # --------------------------------------------------------

    outputs = tf.keras.layers.Reshape(
        (WINDOW_SIZE,),
        name="output_reshape"
    )(x)

    model = tf.keras.Model(
        inputs=inputs,
        outputs=outputs,
        name="TMLP_QAT"
    )

    return model


# ============================================================
# 8. BUILD BASE MODEL
# ============================================================

print("\nBuilding T-MLP QAT model...")
print("----------------------------------------")

base_model = build_tmlp_qat_base()

print("\nBase model:")
base_model.summary()


# ============================================================
# 9. APPLY QUANTIZATION-AWARE TRAINING
# ============================================================

print("\nApplying Quantization-Aware Training...")
print("----------------------------------------")

quantize_model = (
    tfmot.quantization.keras.quantize_model
)

qat_model = quantize_model(
    base_model
)

print("\nQAT model:")
qat_model.summary()


# ============================================================
# 10. COMPILE
# ============================================================

optimizer = tf.keras.optimizers.Adam(
    learning_rate=LEARNING_RATE
)

qat_model.compile(
    optimizer=optimizer,
    loss="mse",
    metrics=[
        tf.keras.metrics.MeanAbsoluteError(
            name="mae"
        )
    ]
)


# ============================================================
# 11. TRAIN
# ============================================================

print("\nStarting QAT training")
print("----------------------------------------")

start_training = time.perf_counter()

history = qat_model.fit(
    train_dataset,
    validation_data=val_dataset,
    epochs=EPOCHS,
    verbose=1
)

training_time = (
    time.perf_counter()
    - start_training
)

print("\nTraining completed.")

print(
    f"Training time: "
    f"{training_time:.2f} seconds"
)


