# 12. TEST EVALUATION
# ============================================================

print("\nEvaluating on TEST dataset")
print("----------------------------------------")

test_loss, test_mae = qat_model.evaluate(
    X_test,
    Y_test,
    batch_size=BATCH_SIZE,
    verbose=1
)

