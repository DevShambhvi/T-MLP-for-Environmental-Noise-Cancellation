EXPECTED_TEST = 100

WINDOW_SIZE = 256
HOP_SIZE = 128

BATCH_SIZE = 32
EPOCHS = 10
LEARNING_RATE = 0.01

MODEL_SAVE_PATH = "/content/TMLP_QAT.keras"


