def load_npz_sample(file_path):
    """
    Load noisy and clean speech from one .npz file.
    """

    data = np.load(file_path)

    noisy = data["noisy_speech"].astype(np.float32)
    clean = data["clean_speech"].astype(np.float32)

    return noisy, clean


# ============================================================
# 4. CREATE SLIDING WINDOWS
# ============================================================

def create_windows(noisy, clean):
    """
    Convert full-length audio into overlapping
    256-sample windows using a 128-sample hop.
    """

    noisy_windows = []
    clean_windows = []

    if len(noisy) != len(clean):
        raise ValueError(
            "Noisy and clean audio lengths do not match."
        )

    if len(noisy) < WINDOW_SIZE:
        return (
            np.empty(
                (0, WINDOW_SIZE),
                dtype=np.float32
            ),
            np.empty(
                (0, WINDOW_SIZE),
                dtype=np.float32
            )
        )

    for start in range(
        0,
        len(noisy) - WINDOW_SIZE + 1,
        HOP_SIZE
    ):

        end = start + WINDOW_SIZE

        noisy_window = noisy[start:end]
        clean_window = clean[start:end]

        noisy_windows.append(noisy_window)
        clean_windows.append(clean_window)

    return (
        np.asarray(
            noisy_windows,
            dtype=np.float32
        ),
        np.asarray(
            clean_windows,
            dtype=np.float32
        )
    )


