# 9. BUILD T-MLP MODEL
# ============================================================

def build_tmlp():

    inputs = Input(
        shape=(WINDOW_SIZE,),
        name="noisy_audio"
    )

    # --------------------------------------------------------
    # Convert waveform vector into temporal representation
    # --------------------------------------------------------

    x = Reshape(
        (WINDOW_SIZE, 1),
        name="temporal_reshape"
    )(inputs)


    # --------------------------------------------------------
    # Feature projection
    # --------------------------------------------------------

    x = Dense(
        PROJECTION_DIM,
        activation="relu",
        name="feature_projection"
    )(x)


    # --------------------------------------------------------
    # Temporal MLP Block 1
    # --------------------------------------------------------

    x = TemporalMLPBlock(
        hidden_dim=HIDDEN_DIM,
        dropout_rate=DROPOUT_RATE,
        name="temporal_mlp_block_1"
    )(x)


    # --------------------------------------------------------
    # Temporal MLP Block 2
    # --------------------------------------------------------

    x = TemporalMLPBlock(
        hidden_dim=HIDDEN_DIM,
        dropout_rate=DROPOUT_RATE,
        name="temporal_mlp_block_2"
    )(x)


    # --------------------------------------------------------
    # Feature reduction
    # --------------------------------------------------------

    x = Dense(
        32,
        activation="relu",
        name="feature_reduction"
    )(x)


    # --------------------------------------------------------
    # Generate one output value per time step
    # --------------------------------------------------------

    x = Dense(
        1,
        activation="linear",
        name="output_projection"
    )(x)


    # --------------------------------------------------------
    # Convert back to waveform
    # --------------------------------------------------------

    outputs = Reshape(
        (WINDOW_SIZE,),
        name="output_waveform"
    )(x)


    model = Model(
        inputs=inputs,
        outputs=outputs,
        name="T_MLP"
    )


    # --------------------------------------------------------
    # Optimizer
    # --------------------------------------------------------

    optimizer = Adam(
        learning_rate=LEARNING_RATE
    )


    # --------------------------------------------------------
    # Compile
    # --------------------------------------------------------

    model.compile(
        optimizer=optimizer,
        loss="mse",
        metrics=["mae"]
    )


    return model


