# 8. TEMPORAL MLP BLOCK
# ============================================================

class TemporalMLPBlock(tf.keras.layers.Layer):
    """
    Temporal MLP block.

    Input:
        (batch, time, features)

    Processing:
        Dense -> ReLU -> Dropout -> Dense

    Residual connection:
        Input + transformed input

    Layer Normalization:
        Applied after residual addition.
    """

    def __init__(
        self,
        hidden_dim=64,
        dropout_rate=0.1,
        **kwargs
    ):
        super().__init__(**kwargs)

        self.dense_1 = Dense(
            hidden_dim,
            activation="relu"
        )

        self.dropout = Dropout(
            dropout_rate
        )

        self.dense_2 = Dense(
            hidden_dim,
            activation=None
        )

        self.add = Add()

        self.layer_norm = LayerNormalization()


    def call(
        self,
        inputs,
        training=None
    ):

        x = self.dense_1(inputs)

        x = self.dropout(
            x,
            training=training
        )

        x = self.dense_2(x)

        x = self.add(
            [inputs, x]
        )

        x = self.layer_norm(x)

        return x


