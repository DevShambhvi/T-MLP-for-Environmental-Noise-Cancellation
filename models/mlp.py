def load_npz_sample(file_path):
    """
    Load noisy and clean speech from one .npz file.
    """

    data = np.load(file_path)

    noisy = data["noisy_speech"].astype(np.float32)
    clean = data["clean_speech"].astype(np.float32)

    return noisy, clean


# ============================================================
# 4. CREATE SLIDING WINDOWS
# ============================================================

def create_windows(noisy, clean):
    """
    Convert full-length audio into overlapping
    256-sample windows with 128-sample hop.
    """

    noisy_windows = []
    clean_windows = []

    if len(noisy) != len(clean):
        raise ValueError(
            "Noisy and clean audio lengths do not match."
        )

    if len(noisy) < WINDOW_SIZE:
        return (
            np.empty((0, WINDOW_SIZE), dtype=np.float32),
            np.empty((0, WINDOW_SIZE), dtype=np.float32)
        )

    for start in range(
        0,
        len(noisy) - WINDOW_SIZE + 1,
        HOP_SIZE
    ):

        end = start + WINDOW_SIZE

        noisy_window = noisy[start:end]
        clean_window = clean[start:end]

        noisy_windows.append(noisy_window)
        clean_windows.append(clean_window)

    return (
        np.asarray(noisy_windows, dtype=np.float32),
        np.asarray(clean_windows, dtype=np.float32)
    )


# ============================================================
# 5. LOAD COMPLETE DATASET
# ============================================================

def load_dataset(file_list, dataset_name):
    """
    Load all .npz files and convert them into
    sliding-window training examples.
    """

    print(
        f"\nLoading {dataset_name} dataset..."
    )

    all_noisy = []
    all_clean = []

    for index, file_path in enumerate(file_list):

        noisy, clean = load_npz_sample(file_path)

        noisy_windows, clean_windows = create_windows(
            noisy,
            clean
        )

        if len(noisy_windows) == 0:
            print(
                f"Warning: skipped {os.path.basename(file_path)} "
                f"(too short)"
            )
            continue

        all_noisy.append(noisy_windows)
        all_clean.append(clean_windows)

        if (index + 1) % 100 == 0:
            print(
                f"Loaded {index + 1}/{len(file_list)} files"
            )

    if not all_noisy:
        raise ValueError(
            f"No valid windows found in {dataset_name} dataset."
        )

    X = np.concatenate(all_noisy, axis=0)
    y = np.concatenate(all_clean, axis=0)

    print(
        f"{dataset_name} windows: {len(X)}"
    )

    return X, y


