def build_mlp():

    model = Sequential([
        Input(shape=(WINDOW_SIZE,)),

        Dense(
            512,
            activation="relu",
            name="dense_512"
        ),

        Dense(
            256,
            activation="relu",
            name="dense_256"
        ),

        Dense(
            WINDOW_SIZE,
            activation="linear",
            name="output"
        )
    ])

    optimizer = Adam(
        learning_rate=LEARNING_RATE
    )

    model.compile(
        optimizer=optimizer,
        loss="mse",
        metrics=["mae"]
    )

    return model


